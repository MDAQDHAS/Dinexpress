-- Helper function to create policies if it doesn't exist
CREATE OR REPLACE FUNCTION create_permissive_policy(table_name TEXT) RETURNS VOID AS $$
BEGIN
    EXECUTE format('DROP POLICY IF EXISTS "permissive_policy" ON public.%I', table_name);
    EXECUTE format('CREATE POLICY "permissive_policy" ON public.%I FOR ALL TO anon, authenticated USING (true) WITH CHECK (true)', table_name);
END;
$$ LANGUAGE plpgsql;

