-- 3. CORE: PRODUCTS (Canteen Menu)
CREATE TABLE public.products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    price DECIMAL(10, 2) NOT NULL,
    category TEXT, -- Breakfast, Lunch, Snacks, Drinks, Cakes, Stationery
    image_url TEXT,
    is_available BOOLEAN DEFAULT true,
    added_at TIMESTAMP WITH TIME ZONE DEFAULT now()
);

-- 4. ACTIVITY: ORDERS (Sales Tracking)
CREATE TABLE public.orders (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
    items_summary TEXT, -- String like "Idli x2, Tea x1" for pie chart analysis
    total_amount DECIMAL(10, 2) NOT NULL,
    status TEXT DEFAULT 'pending', -- pending, accepted, preparing, ready, delivered
    payment_method TEXT DEFAULT 'wallet', -- wallet, cod
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now()
);

-- 5. ACTIVITY: TRANSACTIONS (Wallet/Audit History)
CREATE TABLE public.transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profile_id UUID REFERENCES public.profiles(id) ON DELETE CASCADE,
    amount DECIMAL(10, 2),
    type TEXT, -- Purchase, Recharge, Earned
    description TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now()
);

-- 6. SYSTEM: USER LOGS (Security Audit)
CREATE TABLE public.user_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID,
    email TEXT,
    event_type TEXT, -- login, logout, login-bypass
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now()
);

